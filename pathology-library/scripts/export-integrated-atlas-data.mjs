import fs from 'node:fs'
import path from 'node:path'
import vm from 'node:vm'
import { fileURLToPath } from 'node:url'

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const atlasRoot = process.env.ATLAS_SOURCE_DIR
  ? path.resolve(process.env.ATLAS_SOURCE_DIR)
  : path.resolve(projectRoot, '..', '..', 'pathology-learning-hub-organ-mapping')

const requiredFiles = [
  'atlas-bilingual.js',
  'atlas-curation.js',
  'who-diagnosis-links.js',
  'atlas-expansion.js',
  'app.js',
]

for (const file of requiredFiles) {
  const sourcePath = path.join(atlasRoot, file)
  if (!fs.existsSync(sourcePath)) {
    throw new Error(`Missing Atlas source file: ${sourcePath}`)
  }
}

const context = { window: {}, console }
vm.createContext(context)

for (const file of requiredFiles.slice(0, -1)) {
  vm.runInContext(fs.readFileSync(path.join(atlasRoot, file), 'utf8'), context, {
    filename: file,
  })
}

const appLines = fs.readFileSync(path.join(atlasRoot, 'app.js'), 'utf8').split(/\r?\n/)
const dataEnd = appLines.findIndex((line) => line.startsWith('const sourceCards ='))
if (dataEnd < 0) throw new Error('Could not locate Atlas data boundary in app.js')

vm.runInContext(
  `${appLines.slice(0, dataEnd).join('\n')}\nwindow.__ATLAS_EXPORT__ = { chapters, patterns, cases, verifiedTopicLinks, verifiedWhoMetadata };`,
  context,
  { filename: 'atlas-data-export.js' },
)

const exported = context.window.__ATLAS_EXPORT__
const payload = {
  generatedAt: new Date().toISOString(),
  source: 'pathology-learning-hub-organ-mapping',
  chapters: exported.chapters,
  patterns: exported.patterns,
  cases: exported.cases,
  pathologyOutlinesLinks: exported.verifiedTopicLinks,
  whoLinks: exported.verifiedWhoMetadata,
}

const destination = path.join(projectRoot, 'public', 'atlas-data', 'integrated-atlas.js')
fs.mkdirSync(path.dirname(destination), { recursive: true })
fs.writeFileSync(
  destination,
  `// Generated by scripts/export-integrated-atlas-data.mjs. Do not edit manually.\nwindow.INTEGRATED_ATLAS_DATA=${JSON.stringify(payload)};\n`,
  'utf8',
)

for (const file of ['medical-vi.js', 'search-assistant.js', 'who-catalog.js', 'webpathology-catalog.js']) {
  fs.copyFileSync(path.join(atlasRoot, file), path.join(projectRoot, 'public', 'atlas-data', file))
}

const hmmdContext = { window: {} }
vm.createContext(hmmdContext)
vm.runInContext(fs.readFileSync(path.join(atlasRoot, 'hmmd-data.js'), 'utf8'), hmmdContext, {
  filename: 'hmmd-data.js',
})
const hmmdDataset = hmmdContext.window.HMMD_DATASET
if (!hmmdDataset?.cases?.length) throw new Error('HMMD dataset is empty or invalid')

const hmmdDestination = path.join(projectRoot, 'server', 'data', 'hmmd-data.json')
fs.mkdirSync(path.dirname(hmmdDestination), { recursive: true })
fs.writeFileSync(hmmdDestination, JSON.stringify(hmmdDataset), 'utf8')

console.log(`Exported ${payload.cases.length} Atlas cases and ${payload.chapters.length} organ groups`)
console.log(`Exported ${hmmdDataset.cases.length} HMMD cases to ${hmmdDestination}`)
